let lang = 'en';
export const getLang = () => lang;
export const setLang = (l) => { lang = l; };
export function t(key, params) {
  const e = S[key];
  let s = e ? e[lang === 'ar' ? 1 : 0] : key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? (typeof params[k] === 'number' ? (+params[k]).toFixed(k === 'p' ? 2 : 0) : (typeof params[k] === 'object' ? tr(params[k]) : params[k])) : ''));
  return s;
}
/** Pick the current-language string of an {en, ar} object (or return plain strings). */
export const tr = (o) => (o && typeof o === 'object' ? (o[lang] ?? o.en) : o);
